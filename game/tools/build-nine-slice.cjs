// Panels, labels and ordinary buttons share the approved navigation plates.
// Original departure artwork remains a separate explicit variant.
const path=require('node:path'),fs=require('node:fs/promises');
const dir=path.resolve(__dirname,'../assets/ui-scalable');
(async()=>{
 const old=JSON.parse((await fs.readFile(path.join(dir,'frames.js'),'utf8')).split('export const nineSliceFrames=')[1].trim().replace(/;$/,''));
 const records={};
 for(const [tone,file] of [['blue','normal-frame.png'],['green','selected-frame.png']]){
  records[tone]={file:'../navigation/'+file,width:178,height:144,slice:24,corner:24,alpha:'Approved shared navigation plate; source alpha and fixed corners preserved'};
  records[tone+'-button']={...records[tone]};
  records[tone+'-hero-button']=old[tone+'-hero-button'];
 }
 await fs.writeFile(path.join(dir,'frames.js'),'// Generated by tools/build-nine-slice.cjs\nexport const nineSliceFrames='+JSON.stringify(records)+';\n');
 await fs.writeFile(path.join(dir,'manifest.json'),JSON.stringify({records,rule:'All panels, labels and ordinary buttons use the same 24px corner plate; only departure/start retain original artwork. Explicit compact corner overrides are preserved.'},null,2)+'\n');
 console.log('Built shared compact panel and button definitions without duplicate images');
})().catch(e=>{console.error(e);process.exitCode=1});
