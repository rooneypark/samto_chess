// Purpose-drawn empty UI frames. No screenshot/lettering patches are involved.
const path=require('node:path'),fs=require('node:fs/promises');
const sharp=require('../../design-delivery/v1/a-production/tools/node_modules/sharp');
const root=path.resolve(__dirname,'../..'),dir=path.join(root,'game/assets/ui-scalable');
(async()=>{
 const {data,info}=await sharp(path.join(dir,'button-sheet-v1.png')).ensureAlpha().raw().toBuffer({resolveWithObject:true}),records={};
 for(const [tone,y0,y1] of [['blue',0,512],['green',512,1024]]){
  let left=info.width,right=0,top=y1,bottom=y0;
  for(let y=y0;y<y1;y++)for(let x=0;x<info.width;x++)if(data[(y*info.width+x)*4+3]>=128){left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y);bottom=Math.max(bottom,y);}
  const width=right-left+1,height=bottom-top+1,raw=Buffer.alloc(width*height*4);
  // A button is a closed plate. The generator's alpha can incorrectly mark
  // dark interior pixels transparent: fill INSIDE the measured row contour,
  // while keeping every exterior pixel transparent and all source RGB intact.
  for(let y=0;y<height;y++){
   let a=width,b=-1;for(let x=0;x<width;x++)if(data[((y+top)*info.width+x+left)*4+3]>=128){a=Math.min(a,x);b=x;}
   for(let x=a;x<=b;x++){const i=((y+top)*info.width+x+left)*4,j=(y*width+x)*4;data.copy(raw,j,i,i+3);raw[j+3]=255;}
  }
  await sharp(raw,{raw:{width,height,channels:4}}).png().toFile(path.join(dir,tone+'.png'));
  records[tone]={file:tone+'.png',width,height,slice:112,corner:28,sourceBox:[left,top,width,height],alpha:'Measured source-alpha outer contour, opaque closed interior, transparent exterior, unchanged RGB'};
 }
 await fs.writeFile(path.join(dir,'frames.js'),'// Generated by tools/build-nine-slice.cjs\nexport const nineSliceFrames='+JSON.stringify(records)+';\n');
 await fs.writeFile(path.join(dir,'manifest.json'),JSON.stringify({source:'button-sheet-v1.png',records,rule:'Fixed 28px corners in 941px game design space; only straight edge strips and empty center stretch. Minimum 56px each axis.'},null,2));
 console.log(records);
})().catch(e=>{console.error(e);process.exitCode=1});
