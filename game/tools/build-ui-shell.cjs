// Compose shared chrome from approved UI artwork. No character pixels are used.
const fs=require('node:fs/promises'),path=require('node:path');
const {sharp,frameCutout}=require('./ui-cutout.cjs');
const {buildNavigation}=require('./build-navigation.cjs');
const root=path.resolve(__dirname,'../..'),out=path.join(root,'game/assets/ui-common');
const file=p=>path.join(root,p),gate=file('game/assets/gate-lobby/scene.png');
const crop=(src,x,y,w,h)=>sharp(src).extract({left:x,top:y,width:w,height:h}).png().toBuffer();
const resize=(src,w,h)=>sharp(src).resize(w,h,{kernel:'nearest'}).png().toBuffer();
(async()=>{
 const header=await crop(gate,0,0,941,150),footer=await crop(gate,0,1498,941,174);
 // Keep the original outer frame/corners; a clean source texture replaces content.
 const texture=await resize(file('game/assets/gate-lobby/level.png'),907,118);
 const corners=[];for(const x of [0,907])for(const y of [0,116])corners.push({input:await crop(header,x,y,34,34),left:x,top:y});
 await sharp(header).composite([{input:texture,left:17,top:17},...corners]).png().toFile(path.join(out,'header-frame.png'));
 const title=await frameCutout(gate,[333,19,275,106],{tone:'both',rim:2});
 await sharp(title).composite([{input:await resize(file('game/assets/gate-lobby/dark.png'),223,65),left:26,top:23}]).png().toFile(path.join(out,'header-title.png'));
 await fs.writeFile(path.join(out,'header-home-title.png'),title);
 await sharp(await crop(gate,169,81,130,28)).composite([{input:await sharp({create:{width:118,height:16,channels:4,background:'#192c3e'}}).png().toBuffer(),left:6,top:6}]).png().toFile(path.join(out,'header-xp-frame.png'));
 const footerCorners=[];for(const x of [0,907])for(const y of [0,140])footerCorners.push({input:await crop(footer,x,y,34,34),left:x,top:y});
 await sharp(footer).composite([{input:await resize(file('game/assets/gate-lobby/level.png'),907,158),left:17,top:0},
  {input:await resize(await crop(footer,50,0,140,9),853,9),left:44,top:0},
  {input:await resize(await crop(footer,50,158,140,16),853,16),left:44,top:158},...footerCorners]).png().toFile(path.join(out,'nav-frame.png'));
 // Fit the content below the common 150px header without moving the board/panel.
 for(const screen of ['battle','barracks']){
  const src=file('game/assets/'+(screen==='battle'?'battle-v2':'barracks-v2')+'/scene.png');
  const band=screen==='battle'
   ?await sharp({create:{width:941,height:160,channels:4,background:'#29435d'}}).composite([
      {input:await resize(await crop(src,0,110,941,104),941,84),left:0,top:0},
      {input:await crop(src,0,214,941,76),left:0,top:84}]).png().toBuffer()
   :await resize(await crop(src,0,134,941,111),941,95);
  await fs.writeFile(path.join(out,screen+'-header-content.png'),band);
 }
 const manifest=JSON.parse(await fs.readFile(path.join(out,'manifest.json'))),records=manifest.records;
 await buildNavigation(records);
 await fs.writeFile(path.join(out,'manifest.json'),JSON.stringify(manifest,null,2));
 await fs.writeFile(path.join(out,'components.js'),'// Generated by build-ui-components.cjs then build-ui-shell.cjs\nexport const uiComponents='+JSON.stringify(records)+';\n');
 console.log('Built common 150px header, fixed footer and ten shared tab states');
})().catch(e=>{console.error(e);process.exitCode=1});
